"""Bavya-branded vendor copies of procurement documents for outbound email."""
from __future__ import annotations

from io import BytesIO
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.platform.mail import template


INK = colors.HexColor("#141a2a")
MUTED = colors.HexColor("#697187")
LINE = colors.HexColor("#e5e8ef")
PANEL = colors.HexColor("#fbf7f3")
BRAND = colors.HexColor("#cc004c")
SWEEP = ("#fabc41", "#fb8b00", "#cc004c", "#4d148c")


def _text(value) -> str:
    return (str(value if value is not None and value != "" else "-")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _money(value) -> str:
    return f"{float(value or 0):,.2f}"


def _sweep() -> Table:
    table = Table([["", "", "", ""]], colWidths=[44.5 * mm] * 4, rowHeights=[3 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (index, 0), (index, 0), colors.HexColor(colour))
        for index, colour in enumerate(SWEEP)
    ]))
    return table


def _page_footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setStrokeColor(LINE)
    canvas.line(doc.leftMargin, 11 * mm, A4[0] - doc.rightMargin, 11 * mm)
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 7.5)
    canvas.drawString(doc.leftMargin, 7 * mm, "Generated by SCM ERP | Bavya Health Services Private Limited")
    canvas.drawRightString(A4[0] - doc.rightMargin, 7 * mm, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


def _header(company: template.Company) -> list:
    styles = getSampleStyleSheet()
    right = Paragraph(
        f'<b>{_text(company.legal_name or company.name)}</b><br/>'
        f'<font color="#697187">{_text(company.address)}<br/>'
        f'{_text(" | ".join(x for x in (company.phone, company.email) if x))}</font>',
        ParagraphStyle("VendorDocCompany", parent=styles["BodyText"], alignment=2,
                       fontSize=7.5, leading=10, textColor=INK),
    )
    logo_path: Path = template.LOGO_CIDS["bavya-logo"]
    try:
        logo = Image(str(logo_path), width=42 * mm, height=12 * mm, kind="proportional")
    except OSError:
        logo = Paragraph("<b>BAVYA</b>", styles["Title"])
    table = Table([[logo, right]], colWidths=[70 * mm, 108 * mm])
    table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    return [table, Spacer(1, 3 * mm), _sweep(), Spacer(1, 5 * mm)]


def _pdf(title: str, kicker: str, document_no: str, facts: list[tuple[str, object]],
         columns: list[str], rows: list[list[object]], footer: str,
         company: template.Company) -> bytes:
    stream = BytesIO()
    doc = SimpleDocTemplate(stream, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm,
                            topMargin=14 * mm, bottomMargin=18 * mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("VendorDocTitle", parent=styles["Heading1"], fontName="Helvetica-Bold",
                                 fontSize=17, leading=20, textColor=INK, spaceAfter=2)
    muted_style = ParagraphStyle("VendorDocMuted", parent=styles["BodyText"], fontSize=8,
                                 leading=10, textColor=MUTED)
    fact_label = ParagraphStyle("VendorDocFactLabel", parent=muted_style, fontName="Helvetica-Bold",
                                fontSize=7, leading=9)
    fact_value = ParagraphStyle("VendorDocFactValue", parent=styles["BodyText"], fontName="Helvetica-Bold",
                                fontSize=8.5, leading=11, textColor=INK)
    cell_style = ParagraphStyle("VendorDocCell", parent=styles["BodyText"], fontSize=8,
                                leading=10, textColor=INK)

    story = _header(company)
    band_left = [Paragraph(_text(kicker).upper(), muted_style),
                 Paragraph(_text(title).upper(), title_style),
                 Paragraph(_text(document_no), ParagraphStyle("VendorDocNo", parent=cell_style,
                                                               textColor=BRAND, fontName="Courier-Bold"))]
    band_right = Paragraph("Supplier copy - please retain for your records", ParagraphStyle(
        "VendorDocCopy", parent=muted_style, alignment=2, leading=12))
    band = Table([[band_left, band_right]], colWidths=[122 * mm, 56 * mm])
    band.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), PANEL), ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12), ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
    ]))
    story += [band, Spacer(1, 5 * mm)]

    fact_cells = [[Paragraph(_text(label).upper(), fact_label), Paragraph(_text(value), fact_value)]
                  for label, value in facts if value is not None and value != ""]
    if fact_cells:
        facts_table = Table(fact_cells, colWidths=[43 * mm, 135 * mm])
        facts_table.setStyle(TableStyle([
            ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story += [Paragraph("DOCUMENT PARTICULARS", ParagraphStyle(
            "VendorDocSection", parent=fact_label, fontSize=8, textColor=INK, spaceAfter=5)), facts_table,
            Spacer(1, 5 * mm)]

    story.append(Paragraph("LINE ITEMS", ParagraphStyle(
        "VendorDocItems", parent=fact_label, fontSize=8, textColor=INK, spaceAfter=5)))
    data = [columns] + [[Paragraph(_text(cell), cell_style) for cell in row] for row in rows]
    items = Table(data, repeatRows=1, colWidths=[178 * mm / len(columns)] * len(columns))
    items.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 7.5),
        ("GRID", (0, 0), (-1, -1), 0.35, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story += [items, Spacer(1, 5 * mm), Paragraph(_text(footer), muted_style)]
    doc.build(story, onFirstPage=_page_footer, onLaterPages=_page_footer)
    return stream.getvalue()


def rfq_pdf(rfq, vendor_name: str, company: template.Company,
            item_ids: list[int] | None = None,
            item_quantities: dict[str, float] | None = None) -> bytes:
    allowed = set(item_ids) if item_ids is not None else None
    quantities = item_quantities or {}
    return _pdf(
        "Request for Quotation", "Supplier invitation", rfq.rfq_no,
        [("Supplier", vendor_name), ("RFQ date", rfq.rfq_date), ("Due date", rfq.due_date),
         ("Project", rfq.project_name), ("Title", rfq.title), ("Terms", rfq.terms)],
        ["Code", "Item", "Description", "Qty", "UOM", "Required"],
        [[line.item_code, line.item_name, line.description,
          quantities.get(str(line.item_id), line.quantity), line.uom_code,
          line.required_date] for line in rfq.items
         if allowed is None or line.item_id in allowed],
        "Please sign in to the Supplier Portal to submit your quotation.", company,
    )


def po_pdf(po, company: template.Company) -> bytes:
    facts = [("Supplier", po.vendor_name), ("PO date", po.po_date), ("Expected", po.expected_date),
             ("Project", po.project_name), ("Revision", po.revision_no or "Original"),
             ("Payment terms", po.payment_terms), ("Delivery terms", po.delivery_terms)]
    rows = [[line.item_code, line.item_name, line.quantity, line.uom_code,
             _money(line.rate), _money(line.amount)] for line in po.items]
    rows.append(["", "TOTAL", "", "", "", _money(po.total_amount)])
    return _pdf("Purchase Order", "Order placed on the vendor", po.po_no, facts,
                ["Code", "Item", "Qty", "UOM", "Rate", "Amount"], rows,
                "Please sign in to the Supplier Portal to accept or decline this order.", company)
